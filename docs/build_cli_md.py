"""Regenerate docs/CLI.md from the scripts' own --help output (so the reference can never drift from the code).

    python docs/build_cli_md.py            # from skills/gbc-music/; writes docs/CLI.md
    python docs/build_cli_md.py --check    # exit 1 when CLI.md is stale

Runs every subcommand's --help and `compose.py styles` with the python on PATH (PyBoy is not needed for --help).
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

SKILL = Path(__file__).resolve().parents[1]
SCRIPTS = SKILL / "scripts"
OUT = SKILL / "docs" / "CLI.md"

# (heading, script, args)
SECTIONS = [
    ("compose.py", "compose.py", ["--help"]),
    ("compose.py generate", "compose.py", ["generate", "--help"]),
    ("compose.py compile", "compose.py", ["compile", "--help"]),
    ("compose.py split", "compose.py", ["split", "--help"]),
    ("compose.py events", "compose.py", ["events", "--help"]),
    ("compose.py styles (the library listing)", "compose.py", ["styles"]),
    ("song_rom.py", "song_rom.py", ["--help"]),
    ("song_midi.py", "song_midi.py", ["--help"]),
    ("song_wav.py", "song_wav.py", ["--help"]),
    ("audio_probe.py", "audio_probe.py", ["--help"]),
]


def find(script: str) -> Path:
    c = SCRIPTS / script
    if c.is_file():
        return c
    sys.exit(f"build_cli_md.py: {script} not found under {SCRIPTS}")


def run(script: str, args: list[str]) -> str:
    res = subprocess.run([sys.executable, "-I", str(find(script)), *args], capture_output=True, text=True)
    text = (res.stdout + res.stderr).strip()
    if args == ["styles"]:
        text = "\n".join(l for l in text.splitlines() if not l.startswith("{"))   # drop the JSON line
    return text


def build() -> str:
    parts = ["# CLI reference (generated)",
             "",
             "Generated by `docs/build_cli_md.py` from each script's `--help`; do not edit by hand. Every script prints a",
             "final JSON line `{\"ok\": true, ...}` on success and exits non-zero with a one-line reason on failure.",
             "Run them as `python $SKILL/scripts/<name>.py`, where `$SKILL` is this skill's directory (wherever it is installed).",
             ""]
    for heading, script, args in SECTIONS:
        parts += [f"## {heading}", "", "```text", run(script, args), "```", ""]
    return "\n".join(parts)


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        if OUT.is_file() and OUT.read_text(encoding="utf-8") == text:
            print("CLI.md is current")
            return 0
        print("CLI.md is stale: run python docs/build_cli_md.py")
        return 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(text)} chars)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
